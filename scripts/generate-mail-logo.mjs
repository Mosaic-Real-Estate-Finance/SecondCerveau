// Renders the Mosaic logo for the sign-in mail, as a PNG embedded in the
// message itself (functions/_lib/mail-logo.ts). Mail clients do not draw SVG,
// and a remote image is blocked by default in most of them; an inline
// attachment shows up everywhere, without asking.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const INK = "#020342";
// Twice the width it is shown at in the mail (140 px), for sharp screens.
const WIDTH = 280;

const source = await readFile(new URL("../src/assets/mosaic-logo.svg", import.meta.url), "utf8");
const png = await sharp(Buffer.from(source.replace(/currentColor/g, INK)), { density: 600 })
  .resize({ width: WIDTH })
  .png({ compressionLevel: 9, palette: true })
  .toBuffer();
const { height } = await sharp(png).metadata();

await writeFile(
  fileURLToPath(new URL("../functions/_lib/mail-logo.ts", import.meta.url)),
  `// Generated by scripts/generate-mail-logo.mjs from src/assets/mosaic-logo.svg. Do not edit.
export const MAIL_LOGO = {
  base64: "${png.toString("base64")}",
  width: ${WIDTH / 2},
  height: ${Math.round(height / 2)},
};
`,
);
console.log(`mail logo: ${png.length} bytes, ${WIDTH}x${height}`);
